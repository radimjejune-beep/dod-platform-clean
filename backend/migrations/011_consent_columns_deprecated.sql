-- 011_consent_columns_deprecated.sql
--
-- Согласия живут в таблице user_consents: там редакция текста, дата,
-- кто дал, адрес и браузер — то, что предъявляют при проверке.
--
-- В users остались три колонки от старой схемы, где галочки ставил сам
-- участник. Такое самосогласие несовершеннолетнего юридически ничтожно,
-- поэтому писать в них запрещено: сервер отвечает отказом. Но читать их
-- ничто не мешало, и три экрана читали — родительский кабинет, экран
-- «Согласия» и панель координатора. Все трое показывали «согласий нет»
-- у людей, которые их оформили, и то же самое уходило в выгрузку Excel
-- для проверяющих.
--
-- Колонки НЕ удаляем: в них могли остаться отметки тех, кто заполнял
-- профиль до перехода на новую схему. Это единственный след тех
-- галочек, и уничтожать его нельзя. Вместо удаления помечаем их в самой
-- базе, чтобы следующий, кто откроет таблицу в Adminer, не принял их за
-- действующие.
--
-- Миграция ничего не меняет в данных и безопасна для повторного запуска.

COMMENT ON COLUMN "public"."users"."consent_personal_data" IS
  'УСТАРЕЛО, не заполняется. Действующие согласия: user_consents (consent_type = personal_data).';

COMMENT ON COLUMN "public"."users"."consent_photo_publication" IS
  'УСТАРЕЛО, не заполняется. Действующие согласия: user_consents (consent_type = data_distribution).';

COMMENT ON COLUMN "public"."users"."consent_event_participation" IS
  'УСТАРЕЛО, не заполняется. Действующие согласия: user_consents (consent_type = event_participation).';

COMMENT ON COLUMN "public"."users"."consent_minor_data" IS
  'УСТАРЕЛО, не заполняется. Действующие согласия: таблица user_consents.';

COMMENT ON COLUMN "public"."users"."consent_agreement_date" IS
  'УСТАРЕЛО, не заполняется. Дата согласия: user_consents.given_at.';

COMMENT ON TABLE "public"."user_consents" IS
  'Действующие согласия. Одна строка — одно согласие одного человека: тип, редакция текста, кто дал, когда, адрес и браузер. Отзыв проставляет revoked_at, строка не удаляется.';
