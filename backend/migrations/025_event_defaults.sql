-- Колонка events.max_participants была объявлена с DEFAULT 20, а запрос
-- создания мероприятия её не заполнял вовсе. Поэтому у каждого
-- мероприятия оказывался лимит 20 человек, который никто не задавал, —
-- и запись закрывалась на двадцатом участнике.
--
-- Теперь сервер сохраняет лимит из формы (0 — без ограничений), а
-- значение по умолчанию приводим в соответствие: 0, то есть «не ограничено».
--
-- Применять после 024_event_telemost.sql.
-- ============================================================

ALTER TABLE "public"."events"
  ALTER COLUMN "max_participants" SET DEFAULT 0;

COMMENT ON COLUMN "public"."events"."max_participants" IS
    'Лимит записавшихся. 0 — без ограничений.';

-- Старые мероприятия, созданные до исправления, остались с лимитом 20,
-- которого никто не выбирал. Посмотреть их:
--
-- SELECT id, title, event_date, max_participants, created_at
--   FROM events
--  WHERE max_participants = 20
--  ORDER BY created_at DESC;
--
-- Если среди них нет мероприятий, где 20 действительно задуманы, снять
-- лимит можно так (раскомментируйте и выполните сами — это меняет данные):
--
-- UPDATE events SET max_participants = 0 WHERE max_participants = 20;

