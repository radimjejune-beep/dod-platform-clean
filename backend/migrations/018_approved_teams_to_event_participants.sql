-- УТВЕРЖДЁННЫЕ КОМАНДЫ — В СОСТАВ МЕРОПРИЯТИЯ
-- ============================================================
-- Команда клуба живёт в team_members, состав мероприятия — в
-- event_participants. Утверждение команды заводило запись только в первой
-- таблице, и получались две разные правды об одном и том же выезде:
-- делегация показывала «детей в составе: 1», а мероприятие — «записалось:
-- 0 из 20», список участников был пуст, выгрузка в Excel пустая, а
-- назначенный на выезд тьютор не видел ни одного ребёнка — его дети
-- считаются как раз по event_participants.
--
-- Дальше это делает сам код при утверждении. Здесь — разовый перенос уже
-- утверждённых команд.
--
-- Сопровождающих не переносим: это взрослые, а состав мероприятия — дети.
-- Членов команды без учётной записи тоже: в event_participants лежит
-- ссылка на пользователя.
--
-- Применять после 017_movement_overview.sql.
-- ============================================================

INSERT INTO "public"."event_participants" ("event_id", "user_id", "status", "registered_at")
SELECT ts."event_id", tm."participant_id", 'registered', now()
  FROM "public"."team_members" tm
  JOIN "public"."team_submissions" ts ON ts."id" = tm."submission_id"
 WHERE ts."status" = 'approved'
   AND tm."participant_id" IS NOT NULL
   AND tm."role_in_team" <> 'escort'
ON CONFLICT ("event_id", "user_id") DO NOTHING;
