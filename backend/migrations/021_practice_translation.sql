-- ============================================================
-- ПЕРЕВОД К ЗАДАНИЮ
-- ============================================================
-- Упражнение без перевода работает только у того, кто и так понял
-- предложение. Остальные угадывают форму по окончанию и ничего не
-- запоминают: смысл фразы мимо них проходит.
--
-- Поэтому у каждого задания есть русский перевод — он показывается
-- рядом с вопросом, до ответа, а не после. Это не подсказка к
-- грамматике: перевод не говорит, какую форму выбрать, он говорит, о чём
-- вообще речь.
--
-- Применять после 020_practice.sql.
-- ============================================================

ALTER TABLE "public"."practice_tasks"
  ADD COLUMN IF NOT EXISTS "translation" text;

COMMENT ON COLUMN "public"."practice_tasks"."translation" IS
    'Перевод фразы на русский. Показывается вместе с вопросом до ответа: ребёнок должен понимать, что написано, иначе он угадывает форму, а не выбирает её.';
